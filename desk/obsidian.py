"""Mirror the desk into Samanyu's Obsidian vault so every session starts with full memory.

Writes to the folder in config `obsidian.folder` (skipped silently when it doesn't exist,
e.g. on the GitHub Action runner):

    Trading Desk.md        hub (created once, then left to humans/Claude)
    Desk Memory.md         lessons, watchlist, open theses (Claude-maintained) + auto performance block
    Portfolio.md           auto: account, open/closed positions, stats, equity history
    Trades/Trade 001 NVDA.md   auto block per trade; the "Review" section below it is kept
    Desk Log/<day> Desk.md     auto: the day's decision, regime, setups, all headlines, links to raw files
    Raw/                   verbatim copies of every report and scan

Auto-generated content sits between AUTO markers; anything written outside them is preserved.
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path
from typing import Dict, List, Optional

import pandas as pd

from desk.common import DATA, REPORTS, config, now_ny

START, END = "<!-- desk:auto:start -->", "<!-- desk:auto:end -->"
NOTICE = "> Auto-generated by `desk.py obsidian` from the paper ledger and scans. Edit outside this block only."


def vault_dir() -> Optional[Path]:
    raw = os.environ.get("TRADING_DESK_VAULT") or (config().get("obsidian") or {}).get("folder")
    if not raw:
        return None
    p = Path(os.path.expanduser(raw))
    return p if p.parent.exists() else None   # the project folder may be created; its parent must exist


# ------------------------------------------------------------------ helpers
def _money(x) -> str:
    try:
        return f"${x:,.2f}" if x is not None and x == x else "n/a"
    except TypeError:
        return "n/a"


def _pct(x) -> str:
    return f"{x:.2%}" if isinstance(x, (int, float)) and x == x else "n/a"


def _upsert(path: Path, auto: str, head: str = "", tail: str = "") -> bool:
    """Replace the AUTO block in `path` (creating the file from head/tail if new). Returns True if changed."""
    block = f"{START}\n{NOTICE}\n\n{auto.strip()}\n{END}"
    if path.exists():
        old = path.read_text(encoding="utf-8")
        if START in old and END in old:
            new = old[:old.index(START)] + block + old[old.index(END) + len(END):]
        else:
            new = old.rstrip() + "\n\n" + block + "\n"
    else:
        old = None
        new = (head.rstrip() + "\n\n" if head else "") + block + "\n" + ("\n" + tail.strip() + "\n" if tail else "")
    if new != old:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8")
        return True
    return False


def _write_once(path: Path, text: str) -> bool:
    if path.exists():
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def _trade_name(t: Dict) -> str:
    return f"Trade {t['id']:03d} {t['ticker']}"


def _section(md: str, heading: str) -> str:
    """Body of a '## heading' section in a scan markdown file."""
    m = re.search(rf"^## {re.escape(heading)}.*?$\n(.*?)(?=^## |\Z)", md, re.S | re.M)
    return m.group(1).strip() if m else ""


# ------------------------------------------------------------------ notes
def _trade_note(t: Dict) -> str:
    opt = t.get("option") or {}
    instrument = t["instrument"] + (f" ({opt.get('structure')} {opt.get('expiry')} {opt.get('long_strike')}"
                                    f"{'/' + str(opt.get('short_strike')) if opt.get('short_strike') else ''})" if opt else "")
    fm = {"type": "trade", "trade_id": t["id"], "ticker": t["ticker"], "instrument": t["instrument"],
          "direction": t["direction"], "status": t["status"], "opened": t["opened"], "closed": t.get("closed", ""),
          "setup": t.get("setup", ""), "regime": t.get("regime", ""), "confidence": t.get("confidence", ""),
          "pnl": round(t["pnl"], 2) if "pnl" in t else "", "r_multiple": round(t["r_multiple"], 2) if "r_multiple" in t else ""}
    mult = 100 if t["instrument"] == "option" else 1
    if t["status"] == "open":
        mark = t.get("last_mark", t["entry_price"])
        sign = -1 if (t["direction"] == "SHORT" and t["instrument"] == "stock") else 1
        unreal = sign * (mark - t["entry_price"]) * t["quantity"] * mult
        result = f"**OPEN** · last mark {_money(mark)} → unrealized **{_money(unreal)}** ({unreal / t['risk']:+.2f}R)"
    else:
        result = (f"**CLOSED {t.get('closed')}** at {_money(t.get('exit_price'))} ({t.get('exit_reason')}) → "
                  f"P&L **{_money(t.get('pnl'))}** ({_pct(t.get('return_pct'))}, {t.get('r_multiple', 0):+.2f}R, "
                  f"{t.get('holding_days')} days)")
    lines = [f"# {_trade_name(t)}: {t['direction']} {t['ticker']}", "",
             f"Status: {result}", "",
             "| Field | Value |", "|---|---|",
             f"| Opened | {t['opened']} ET |", f"| Instrument | {instrument} |",
             f"| Quantity | {t['quantity']} |", f"| Entry | {_money(t['entry_price'])} |",
             f"| Stop / target | {_money(t['stop'])} / {_money(t['target'])} |",
             f"| Cost | {_money(t['cost'])} |", f"| Risk (max loss) | {_money(t['risk'])} |",
             f"| Setup · regime · confidence | {t.get('setup')} · {t.get('regime')} · {t.get('confidence')} |", "",
             "**Thesis:** " + (t.get("reason") or "n/a"), "",
             "**Catalyst:** " + (t.get("catalyst") or "n/a"), "",
             f"Day opened: [[{t['opened'][:10]} Desk]] · Back to [[Portfolio]] · [[Desk Memory]]"]
    front = "---\n" + "\n".join(f"{k}: {json.dumps(v) if isinstance(v, str) else v}" for k, v in fm.items()) + \
            "\ntags: [trade, paper-trading]\n---"
    return front, "\n".join(lines)


def _portfolio(book: Dict) -> str:
    from desk import paper

    acct = paper.account(book)
    tr = book["trades"]
    open_t = [t for t in tr if t["status"] == "open"]
    closed = [t for t in tr if t["status"] == "closed"]
    L = [f"# Paper Portfolio ($30,000 start)", "",
         f"*Synced {now_ny():%Y-%m-%d %H:%M} ET. Marks are the last ledger update (Yahoo, delayed). Paper only.*", "",
         "| Equity | Cash | Open value | Realized | Unrealized | Open risk | Options exposure | Return |",
         "|---|---|---|---|---|---|---|---|",
         f"| {_money(acct['equity'])} | {_money(acct['cash'])} | {_money(acct['open_market_value'])} | "
         f"{_money(acct['realized_pnl'])} | {_money(acct['unrealized_pnl'])} | {_money(acct['open_risk'])} "
         f"({_pct(acct['open_risk'] / acct['equity'])}) | {_money(acct['options_exposure'])} | {_pct(acct['total_return'])} |", "",
         f"## Open positions ({len(open_t)})"]
    if open_t:
        L += ["| Trade | Dir | Qty | Entry | Mark | Stop | Target | Risk | Opened |", "|---|---|---|---|---|---|---|---|---|"]
        for t in open_t:
            L.append(f"| [[{_trade_name(t)}]] | {t['direction']} | {t['quantity']} | {_money(t['entry_price'])} | "
                     f"{_money(t.get('last_mark'))} | {_money(t['stop'])} | {_money(t['target'])} | {_money(t['risk'])} | {t['opened']} |")
    else:
        L.append("None. All cash.")
    L += ["", f"## Closed trades ({len(closed)})"]
    if closed:
        L += ["| Trade | Dir | Entry | Exit | P&L | R | Days | Exit reason | Setup |", "|---|---|---|---|---|---|---|---|---|"]
        for t in sorted(closed, key=lambda x: x.get("closed", ""), reverse=True):
            L.append(f"| [[{_trade_name(t)}]] | {t['direction']} | {_money(t['entry_price'])} | {_money(t.get('exit_price'))} | "
                     f"{_money(t.get('pnl'))} | {t.get('r_multiple', 0):+.2f} | {t.get('holding_days')} | {t.get('exit_reason')} | {t.get('setup')} |")
    else:
        L.append("None yet.")
    L += ["", "## Statistics (closed trades)", "```json", json.dumps(paper.statistics(book), indent=1, default=str), "```"]
    eq = paper.EQUITY
    if eq.exists():
        df = pd.read_csv(eq).tail(30)
        L += ["", "## Equity history (last 30 updates)", "| Date | Equity | Cash | Open risk | Return |", "|---|---|---|---|---|"]
        for _, r in df.iloc[::-1].iterrows():
            L.append(f"| {r['date']} | {_money(r['equity'])} | {_money(r['cash'])} | {_money(r['open_risk'])} | {_pct(r['total_return'])} |")
    return "\n".join(L)


def _performance_block(book: Dict) -> str:
    from desk import paper

    st = paper.statistics(book)
    L = ["## Performance memory (auto)", f"*Synced {now_ny():%Y-%m-%d %H:%M} ET.*", "",
         f"- Closed trades: {st['closed_trades']} · open: {st['open_trades']}"]
    if st["closed_trades"]:
        L += [f"- Win rate {_pct(st['win_rate'])} · avg win {_money(st['avg_win'])} · avg loss {_money(st['avg_loss'])} · "
              f"profit factor {st['profit_factor']:.2f} · avg R {st['avg_r_multiple']:+.2f} · {st['milestone']}"]
        for col in ("setup", "regime", "instrument", "direction"):
            rows = st.get(f"by_{col}", {})
            if rows:
                L.append(f"- By {col}: " + "; ".join(f"**{k}** {v['trades']} trades, win {v['win_rate']:.0%}, "
                                                      f"P&L {_money(v['total_pnl'])}" for k, v in rows.items()))
        L.append("- Sample sizes under ~20 trades per bucket are noise; don't drop a setup on a handful of results.")
    else:
        L.append("- No closed trades yet, so there's nothing to learn from results. Judge process, not P&L.")
    return "\n".join(L)


def _desk_log(day: str, files: List[Path], brief: Optional[Dict], book: Dict) -> str:
    report = next((f for f in files if f.name == f"{day}_report.md"), None)
    scans = sorted(f for f in files if "_scan" in f.name)
    L = [f"# Desk log: {day}", ""]
    if report:
        txt = report.read_text(encoding="utf-8")
        dec = re.search(r"FINAL DECISION:\s*\**([A-Z /-]+?)\**\s*$", txt, re.M)
        reg = re.search(r"MARKET REGIME:\s*\**([A-Z /-]+?)\**[\s(]", txt)
        L += [f"**Decision:** {dec.group(1).strip() if dec else 'see report'} · **Regime (report):** "
              f"{reg.group(1).strip() if reg else 'n/a'}", ""]
        for title in ("BEST TRADE OF THE DAY", "INTRADAY UPDATE", "CLOSE UPDATE"):
            for m in re.finditer(rf"^{title}.*?$\n(.*?)(?=^━|\Z)", txt, re.S | re.M):
                L += [f"### {m.group(0).splitlines()[0].strip()}", m.group(1).strip(), ""]
    else:
        L += ["No analyst report written this day (scan data only).", ""]
    if brief:
        r = brief.get("regime", {})
        L += ["## Latest scan snapshot", f"Generated {brief.get('generated')} (session: {brief.get('session')})", "",
              f"- Rule regime: **{r.get('regime')}** (score {r.get('score')}) · SPY {r.get('spy', 0):.2f} · VIX {r.get('vix', 0):.2f} "
              f"vs VIX3M {r.get('vix3m', 0):.2f} · breadth {_pct(r.get('breadth_above_50d'))}",
              f"- Fed proxy: {brief.get('fed_proxy', {}).get('signal')}",
              f"- Data gaps: {', '.join(brief.get('data_gaps') or []) or 'none'}"]
        if brief.get("setups"):
            L += ["", "| Setup | Dir | Type | Entry | Stop | Target | R:R | Score |", "|---|---|---|---|---|---|---|---|"]
            for s in brief["setups"][:15]:
                L.append(f"| {s['ticker']} | {s['direction']} | {', '.join(s['setups'])} | {s['entry']:.2f} | {s['stop']:.2f} | "
                         f"{s['target']:.2f} | {s['reward_risk']:.1f} | {s['score']:.2f} |")
        L.append("")
    # every headline seen across the day's scans, de-duplicated by title (keeps the highest score)
    best: Dict[str, List[str]] = {}
    for f in scans:
        for line in _section(f.read_text(encoding="utf-8"), "Top headlines").splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) < 6 or cells[0].lower() == "score" or set(cells[0]) <= set("-: "):
                continue
            try:
                sc = float(cells[0])
            except ValueError:
                continue
            key = re.sub(r"\W+", " ", cells[-1].lower()).strip()
            if key not in best or sc > float(best[key][0]):
                best[key] = cells
    if best:
        rows = sorted(best.values(), key=lambda c: -float(c[0]))
        L += [f"## Headlines seen today ({len(rows)}, triage score 0-10)", "| Score | Time | Source | Tags | Ticker | Headline |",
              "|---|---|---|---|---|---|"] + ["| " + " | ".join(c.replace("|", "/") for c in r[:6]) + " |" for r in rows] + [""]
    for f in scans[-1:]:
        mm = _section(f.read_text(encoding="utf-8"), "News vs. price")
        if mm:
            L += ["## News vs. price (latest scan)", mm, ""]
    trades = [t for t in book["trades"] if t["opened"][:10] == day or (t.get("closed") or "")[:10] == day]
    L += ["## Paper trades touched today"] + ([f"- [[{_trade_name(t)}]]: {t['direction']} {t['ticker']} ({t['status']})"
                                                for t in trades] or ["- none"])
    L += ["", "## Raw files"] + [f"- [[Raw/{f.stem}|{f.name}]]" for f in files]
    L += ["", "Back to [[Trading Desk]] · [[Portfolio]] · [[Desk Memory]]"]
    return "\n".join(L)


