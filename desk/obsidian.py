# ------------------------------------------------------------------ main
def sync(quiet: bool = False) -> Dict[str, object]:
    root = vault_dir()
    if root is None:
        return {"skipped": "vault folder not configured or not found"}
    from desk import paper

    book = paper.load()
    day = now_ny().strftime("%Y-%m-%d")
    changed: List[str] = []

    def mark(ok: bool, p: Path):
        if ok:
            changed.append(str(p.relative_to(root)))

    first = min([t["opened"][:10] for t in book["trades"]] + [day])
    mark(_write_once(root / "Trading Desk.md", HUB.format(day=first)), root / "Trading Desk.md")
    mem = root / "Desk Memory.md"
    mark(_write_once(mem, MEMORY.format(day=first)), mem)
    mark(_upsert(mem, _performance_block(book)), mem)
    mark(_upsert(root / "Portfolio.md", _portfolio(book), head="---\ntype: resource\ntags: [trading, portfolio]\n---"),
         root / "Portfolio.md")

    for t in book["trades"]:
        front, body = _trade_note(t)
        p = root / "Trades" / f"{_trade_name(t)}.md"
        ok = _upsert(p, body, head=front, tail="## Review (what happened, what I learned)\n- ")
        if ok and p.exists():   # keep frontmatter current too
            txt = p.read_text(encoding="utf-8")
            if txt.startswith("---") and txt.count("---") >= 2:
                end = txt.index("---", 3) + 3
                p.write_text(front + txt[end:], encoding="utf-8")
        mark(ok, p)

    # raw copies of every report/scan, and one desk log per day
    by_day: Dict[str, List[Path]] = {}
    for f in sorted(REPORTS.glob("20??-??-??_*.md")):
        dst = root / "Raw" / f.name
        src = f.read_text(encoding="utf-8")
        if not dst.exists() or dst.read_text(encoding="utf-8") != src:
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_text(src, encoding="utf-8")
            mark(True, dst)
        by_day.setdefault(f.name[:10], []).append(f)
    for d, files in by_day.items():
        bj = DATA / "briefs" / f"{d}.json"
        brief = json.loads(bj.read_text()) if bj.exists() else None
        p = root / "Desk Log" / f"{d} Desk.md"
        mark(_upsert(p, _desk_log(d, files, brief, book),
                     head=f"---\ntype: desk-log\ndate: {d}\ntags: [trading, desk-log]\n---",
                     tail="## My notes\n- "), p)
    out = {"vault": str(root), "changed": changed, "synced": f"{now_ny():%Y-%m-%d %H:%M} ET"}
    if not quiet:
        print(f"Obsidian sync → {root}\n  {len(changed)} file(s) updated" + "".join(f"\n  · {c}" for c in changed))
    return out


def safe_sync() -> None:
    """Called after desk commands; never lets a vault problem break trading research."""
    try:
        r = sync(quiet=True)
        if r.get("changed"):
            print(f"(Obsidian: {len(r['changed'])} note(s) updated)")
    except Exception as exc:  # pragma: no cover
        print(f"(Obsidian sync skipped: {exc.__class__.__name__}: {exc})")
